#Operações simples
a = 80
b = 30

print("Soma: ", a + b)
print("Subtração: ", a - b)
print("Multiplicação: ", a * b)
print("Divisão Float: ", a / b)
print("Divisão Inteira: ", a // b)
print("Exponênciação: ", a ** b)

c = a // b
print("Verificando o valor C como float: ", float(c))

#Exemplos módulo 
modulo = 30 % 4
print("Resto da divisão de 30 por 4: ", modulo)

modulo = -30 % 4
print("Resto da divisão de -30 por 4: ", modulo)