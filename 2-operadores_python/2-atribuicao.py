# 1. atribuição simples (=)

qtd = 80
print("Valor inicial de qtd: ", qtd)

# 2. atribuição reduzida adição (+=)

qtd+=90
print("Após qtd +=90:0 ", qtd)

# 3. atribuição reduzida subtração (-=)

qtd-=100
print("Após qtd -=100: ", qtd)

# 4. atribuição reduzida multiplicação (*=)

qtd*=2
print("Após qtd *=2: ", qtd)

# 4. atribuição reduzida divisão (/=)

qtd/=10
print("Após qtd /=10: ", qtd)

#           Print produzido
# Valor inicial de qtd:  80
# Após qtd +=90:0  170#b
# Após qtd -=100:  70
# Após qtd *=2:  140
# Após qtd /=10:  14.0



